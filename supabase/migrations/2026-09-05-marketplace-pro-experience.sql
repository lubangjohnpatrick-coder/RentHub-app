-- GoRentHive marketplace pro experience
-- Flexible pricing, owner availability blocks, saved searches, notifications,
-- business verification, richer agreements/condition evidence and two-phase QR handover.

create table if not exists public.listing_pricing (
  listing_id bigint primary key references public.listings(id) on delete cascade,
  hourly_rate integer check (hourly_rate is null or hourly_rate > 0),
  daily_rate integer check (daily_rate is null or daily_rate > 0),
  weekly_rate integer check (weekly_rate is null or weekly_rate > 0),
  monthly_rate integer check (monthly_rate is null or monthly_rate > 0),
  hourly_enabled boolean not null default false,
  daily_enabled boolean not null default true,
  weekly_enabled boolean not null default false,
  monthly_enabled boolean not null default false,
  minimum_hours integer not null default 1 check (minimum_hours between 1 and 168),
  minimum_days integer not null default 1 check (minimum_days between 1 and 365),
  created_at bigint not null default ((extract(epoch from now()) * 1000)::bigint),
  updated_at bigint not null default ((extract(epoch from now()) * 1000)::bigint)
);

create table if not exists public.listing_availability_blocks (
  id bigint generated by default as identity primary key,
  listing_id bigint not null references public.listings(id) on delete cascade,
  owner_id uuid not null references public.users(id) on delete cascade,
  start_at bigint not null,
  end_at bigint not null,
  note text not null default '',
  created_at bigint not null default ((extract(epoch from now()) * 1000)::bigint),
  check (end_at >= start_at)
);
create index if not exists listing_availability_blocks_listing_idx on public.listing_availability_blocks(listing_id,start_at,end_at);

create table if not exists public.saved_searches (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.users(id) on delete cascade,
  name text not null default 'Saved search',
  query_text text not null default '',
  category_id bigint references public.categories(id) on delete set null,
  city text not null default '',
  radius_km integer check (radius_km is null or radius_km between 1 and 100),
  max_price integer check (max_price is null or max_price >= 0),
  alerts_enabled boolean not null default true,
  last_checked_at bigint not null default 0,
  created_at bigint not null default ((extract(epoch from now()) * 1000)::bigint),
  updated_at bigint not null default ((extract(epoch from now()) * 1000)::bigint)
);
create index if not exists saved_searches_user_idx on public.saved_searches(user_id);

create table if not exists public.notification_preferences (
  user_id uuid primary key references public.users(id) on delete cascade,
  booking_updates boolean not null default true,
  messages boolean not null default true,
  saved_search_alerts boolean not null default true,
  reminders boolean not null default true,
  owner_opportunities boolean not null default true,
  updated_at bigint not null default ((extract(epoch from now()) * 1000)::bigint)
);


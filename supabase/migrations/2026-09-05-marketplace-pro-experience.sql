create table if not exists public.vehicle_incidents (
  id bigint generated by default as identity primary key,
  booking_id bigint not null references public.bookings(id) on delete cascade,
  reporter_id uuid not null references public.users(id),
  incident_type text not null,
  description text not null default '',
  location_city text not null default '',
  evidence text not null default '[]',
  police_report_reference text not null default '',
  insurance_reference text not null default '',
  status text not null default 'open' check (status in ('open','under_review','resolved','closed')),
  created_at bigint not null default ((extract(epoch from now()) * 1000)::bigint),
  updated_at bigint not null default ((extract(epoch from now()) * 1000)::bigint)
);
create index if not exists vehicle_incidents_booking_idx on public.vehicle_incidents(booking_id);

create table if not exists public.booking_handover_tokens (
  booking_id bigint not null references public.bookings(id) on delete cascade,
  phase text not null check (phase in ('pickup','return')),
  token_hash text not null,
  pin_hash text not null,
  generated_by uuid not null references public.users(id) on delete cascade,
  scanned_by uuid references public.users(id) on delete set null,
  scanned_at bigint,
  renter_confirmed_at bigint,
  owner_confirmed_at bigint,
  expires_at bigint not null,
  attempts integer not null default 0 check (attempts between 0 and 20),
  used_at bigint,
  created_at bigint not null default ((extract(epoch from now()) * 1000)::bigint),
  updated_at bigint not null default ((extract(epoch from now()) * 1000)::bigint),
  primary key (booking_id, phase)
);


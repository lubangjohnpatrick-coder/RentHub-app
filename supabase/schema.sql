-- ============================================================
-- FINANCIAL RPC FUNCTIONS (SECURITY DEFINER)
-- Called via supabase.rpc() by the financial server.
-- `security definer` lets a limited-role caller perform these
-- privileged money movements without full table access.
-- ============================================================
create or replace function public.ledger_entry(
  p_booking_id bigint,
  p_user_id uuid,
  p_type text,
  p_amount integer,
  p_meta text default '{}'
)
returns table (entry_id bigint, new_balance integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  before_balance integer;
begin
  if p_user_id is not null then
    select coalesce(wallet_balance,0) into before_balance from public.users where id = p_user_id;
  else
    before_balance := 0;
  end if;

  insert into public.ledger_entries (booking_id, user_id, type, amount, balance_after, meta, created_at)
  values (p_booking_id, p_user_id, p_type, p_amount, before_balance + p_amount, p_meta,
          (extract(epoch from now())*1000)::bigint)
  returning id into entry_id;

  if p_user_id is not null then
    update public.users set wallet_balance = wallet_balance + p_amount, updated_at = (extract(epoch from now())*1000)::bigint
    where id = p_user_id;
  end if;

  new_balance := before_balance + p_amount;
  return query select entry_id, new_balance;
end;
$$;

-- SECURITY: these are SECURITY DEFINER (bypass RLS) and MUST only be callable
-- by the financial server's service_role connection. Granting them to
-- anon/authenticated would let any browser user mint/deduct wallet money.
revoke all on function public.ledger_entry(bigint, uuid, text, integer, text) from public;
revoke all on function public.ledger_entry(bigint, uuid, text, integer, text) from anon, authenticated;
grant execute on function public.ledger_entry(bigint, uuid, text, integer, text) to service_role;

create or replace function public.get_user_balance(p_user_id uuid)
returns integer
language sql
security definer
set search_path = public
as $$
  select coalesce(wallet_balance,0) from public.users where id = p_user_id;
$$;

revoke all on function public.get_user_balance(uuid) from public;
revoke all on function public.get_user_balance(uuid) from anon, authenticated;
grant execute on function public.get_user_balance(uuid) to service_role;

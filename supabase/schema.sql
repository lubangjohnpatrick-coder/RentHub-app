-- ---- public read policies ----
-- SECURITY: `users` holds password_hash, email, phone, wallet_balance,
-- id_number and id_selfie. We only expose the SAFE public profile columns to
-- anon/authenticated read. The own user's private fields (email, phone,
-- wallet_balance) are served by the server /auth/me + /wallet endpoints using
-- the service_role key. Column-level privileges are enforced here.
drop policy if exists "users read public users" on public.users;
create policy "users read public users" on public.users for select using (true);
revoke select on public.users from anon, authenticated;
grant select (
  id, full_name, avatar, role, is_owner, is_business,
  mobile_verified, email_verified, identity_status, identity_level,
  address, barangay, city, province, latitude, longitude,
  location_status, location_verified_by, location_verified_at,
  vessel_rating, review_count, successful_rentals, cancelled_rentals,
  referral_code
) on public.users to anon, authenticated;

-- own-user private reads (email, phone, wallet_balance) allowed only for the
-- row matching the authenticated user; the value-level policy cannot inspect
-- columns, so we rely on these columns being non-selectable via the column
-- grants above and served through the server instead. Profile rows are created
-- by the SECURITY DEFINER handle_new_user trigger on auth signup.
revoke insert on public.users from anon, authenticated;

